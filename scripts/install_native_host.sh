#!/bin/bash
# Register the Chromium native-messaging host for Internet Downloader.
#
# The host MUST be the copy inside the app bundle (Contents/Helpers), never a
# bare .build/release binary: that is what allows the host to launch the app it
# belongs to. Chromium is given a small wrapper that exports IDM_APP_PATH before
# exec'ing the bundled helper, so a download started while the app is closed
# still auto-launches the exact release bundle (and a stale copy cannot win).
set -euo pipefail

DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )/.." && pwd )"
cd "$DIR"

APP_NAME="Internet Downloader.app"
HOST_BINARY_NAME="internet-downloader-host"
VERSION_FILE="$DIR/VERSION"
APPVERSION_SWIFT="$DIR/Sources/DownloaderCore/AppVersion.swift"
SUPPORT_DIR="$HOME/Library/Application Support/InternetDownloader"
WRAPPER="$SUPPORT_DIR/native-host-wrapper.sh"

die() { echo "ERROR: $*" >&2; exit 1; }
note() { echo "  -> $*"; }

# Read `public static let <name> = "<value>"` from AppVersion.swift.
swift_string_literal() {
    local file="$1" name="$2"
    [ -f "$file" ] || return 0
    sed -n -E "s/.*static let ${name}[[:space:]]*=[[:space:]]*\"([^\"]*)\".*/\1/p" "$file" | head -n 1
}

bundle_version() {
    local plist="$1/Contents/Info.plist"
    [ -f "$plist" ] || return 1
    /usr/bin/plutil -extract CFBundleShortVersionString raw -o - "$plist" 2>/dev/null || return 1
}

# A bundle is usable only when it ships the helper AND was built from this VERSION.
# The bug this guards against is a bundle that has a helper but is stale, so a
# plain "file exists" check is not enough.
bundle_usable() {
    local app="$1"
    [ -d "$app" ] || return 1
    [ -x "$app/Contents/Helpers/$HOST_BINARY_NAME" ] || return 1
    [ "$(bundle_version "$app")" = "$APP_VERSION" ] || return 1
}

# --- Version / identity constants come from the same source the app uses. ---
[ -f "$VERSION_FILE" ] || die "Missing $VERSION_FILE (repo-root VERSION file)."
APP_VERSION="$(tr -d '[:space:]' < "$VERSION_FILE")"
[ -n "$APP_VERSION" ] || die "VERSION is empty."

[ -f "$APPVERSION_SWIFT" ] || die "Missing $APPVERSION_SWIFT (AppVersion is the single source for host name/origin)."
HOST_NAME="$(swift_string_literal "$APPVERSION_SWIFT" nativeHostName)"
ALLOWED_ORIGIN="$(swift_string_literal "$APPVERSION_SWIFT" extensionAllowedOrigin)"
[ -n "$HOST_NAME" ] || die "Cannot read AppVersion.nativeHostName from $APPVERSION_SWIFT."
[ -n "$ALLOWED_ORIGIN" ] || die "Cannot read AppVersion.extensionAllowedOrigin from $APPVERSION_SWIFT."

# --- 1. Find (or build) an app bundle that contains the native host. ---
APP_PATH=""
BUILT_STAGE=0
if [ -n "${IDM_APP_PATH:-}" ]; then
    APP_PATH="$IDM_APP_PATH"
    [ -x "$APP_PATH/Contents/Helpers/$HOST_BINARY_NAME" ] || \
        die "IDM_APP_PATH=$APP_PATH does not contain an executable Contents/Helpers/$HOST_BINARY_NAME."
    FOUND_VERSION="$(bundle_version "$APP_PATH")" || FOUND_VERSION="unknown"
    [ "$FOUND_VERSION" = "$APP_VERSION" ] || \
        die "IDM_APP_PATH=$APP_PATH is version '$FOUND_VERSION' but VERSION expects $APP_VERSION; rebuild it or point IDM_APP_PATH at a current bundle."
elif bundle_usable "$DIR/dist/$APP_NAME"; then
    APP_PATH="$DIR/dist/$APP_NAME"
elif [ -n "${IDM_BUILD_DIR:-}" ] && bundle_usable "$IDM_BUILD_DIR/$APP_NAME"; then
    APP_PATH="$IDM_BUILD_DIR/$APP_NAME"
else
    STAGE_DIR="${IDM_BUILD_DIR:-$DIR/.runtime/release-staging/$(date +%Y%m%d-%H%M%S)}"
    if [ -e "$STAGE_DIR" ]; then
        die "Release stage already exists but is not usable (missing helper or version != $APP_VERSION): $STAGE_DIR. Choose a fresh IDM_BUILD_DIR or remove it."
    fi
    echo "==> No installed dist bundle with version $APP_VERSION; building a staged release..."
    IDM_BUILD_DIR="$STAGE_DIR" bash "$DIR/scripts/build_app.sh"
    APP_PATH="$STAGE_DIR/$APP_NAME"
    BUILT_STAGE=1
    bundle_usable "$APP_PATH" || die "Build finished but $APP_PATH is not a usable bundle for version $APP_VERSION."
fi

HOST_PATH="$APP_PATH/Contents/Helpers/$HOST_BINARY_NAME"
chmod +x "$HOST_PATH"

# --- 2. Wrapper: Chrome/Chromium launch this, not the binary directly. ---
mkdir -p "$SUPPORT_DIR"
chmod 700 "$SUPPORT_DIR"
cat > "$WRAPPER" <<EOF
#!/bin/bash
# Generated by scripts/install_native_host.sh. Chromium launches this wrapper
# instead of the binary directly so the host knows which app bundle to launch.
export IDM_APP_PATH="$APP_PATH"
exec "$HOST_PATH" "\$@"
EOF
chmod 700 "$WRAPPER"

MANIFEST_CONTENT="$(cat <<EOF
{
  "name": "$HOST_NAME",
  "description": "Internet Downloader Native Messaging Host for macOS",
  "path": "$WRAPPER",
  "type": "stdio",
  "allowed_origins": [
    "$ALLOWED_ORIGIN"
  ]
}
EOF
)"

# --- 3. Point every Chromium-family NativeMessagingHosts manifest at the wrapper. ---
TARGET_DIRS=(
    "$HOME/Library/Application Support/Google/Chrome/NativeMessagingHosts"
    "$HOME/Library/Application Support/Chromium/NativeMessagingHosts"
    "$HOME/Library/Application Support/Microsoft Edge/NativeMessagingHosts"
    "$HOME/Library/Application Support/BraveSoftware/Brave-Browser/NativeMessagingHosts"
    "$HOME/Library/Application Support/Arc/User Data/NativeMessagingHosts"
)

INSTALLED=0
for target in "${TARGET_DIRS[@]}"; do
    if mkdir -p "$target" 2>/dev/null; then
        printf '%s\n' "$MANIFEST_CONTENT" > "$target/$HOST_NAME.json"
        note "manifest: $target/$HOST_NAME.json"
        INSTALLED=$((INSTALLED + 1))
    fi
done

[ "$INSTALLED" -gt 0 ] || die "Could not write any NativeMessagingHosts manifest under $HOME/Library/Application Support."

# --- 4. Summary and next steps. ---
echo
echo "=========================================================="
echo "  Native Messaging Host đã đăng ký (${INSTALLED} trình duyệt)"
echo "  - App bundle   : $APP_PATH"
echo "  - App version  : $APP_VERSION"
echo "  - Host binary  : $HOST_PATH"
echo "  - Chrome wrapper: $WRAPPER (IDM_APP_PATH=$APP_PATH)"
if [ "$BUILT_STAGE" = "1" ]; then
    echo "  - Bundle đang ở staging, chưa nằm trong dist/. Cài release rồi chạy lại script này:"
    echo "      python3 scripts/install_release.py --stage \"$(dirname "$APP_PATH")\""
    echo "      bash scripts/install_native_host.sh"
fi
echo "  Bước tiếp theo:"
echo "    1. chrome://extensions -> Reload extension 'Internet Downloader Integration Module'"
echo "    2. Reload tab đang mở, rồi bấm 'Tải video này' khi app đang tắt để kiểm tra auto-launch"
echo "=========================================================="
