#!/usr/bin/env python3
"""Install a verified staged release after the desktop app has been quit."""
import argparse
import base64
import hashlib
import json
import os
from pathlib import Path
import plistlib
import re
import shutil
import sqlite3
import subprocess
from datetime import datetime

APP_NAME = 'Internet Downloader.app'
HOST_BINARY_RELATIVE = 'Contents/Helpers/internet-downloader-host'
EXTENSION_ID_RE = re.compile(r'^chrome-extension://([a-p]{32})/$')


def checksum(path):
    result = hashlib.sha256()
    with path.open('rb') as stream:
        for part in iter(lambda: stream.read(65536), b''):
            result.update(part)
    return result.hexdigest()


def swift_string(source, name):
    match = re.search(r'\bstatic let ' + re.escape(name) + r'\s*=\s*"([^"]*)"', source)
    if not match:
        raise SystemExit(f'Cannot read AppVersion.{name} from Sources/DownloaderCore/AppVersion.swift')
    return match.group(1)


def swift_int(source, name):
    match = re.search(r'\bstatic let ' + re.escape(name) + r'\s*=\s*(\d+)', source)
    if not match:
        raise SystemExit(f'Cannot read AppVersion.{name} from Sources/DownloaderCore/AppVersion.swift')
    return int(match.group(1))


def expected_identity(root):
    """Everything a staged release must agree with, read from the repo.

    AppVersion.swift + repo-root VERSION are the single source; the staged
    bundle/extension are only checked against them, so a stale stage cannot be
    installed and a bump cannot be forgotten in the installer.
    """
    version = (root / 'VERSION').read_text().strip()
    if not version:
        raise SystemExit('VERSION is empty')
    source = (root / 'Sources/DownloaderCore/AppVersion.swift').read_text()
    constants = {
        'appVersion': swift_string(source, 'appVersion'),
        'extensionVersion': swift_string(source, 'extensionVersion'),
        'nativeHostName': swift_string(source, 'nativeHostName'),
        'bundleIdentifier': swift_string(source, 'bundleIdentifier'),
        'appExecutableName': swift_string(source, 'appExecutableName'),
        'extensionAllowedOrigin': swift_string(source, 'extensionAllowedOrigin'),
        'protocolVersion': swift_int(source, 'protocolVersion'),
    }
    if version != constants['appVersion']:
        raise SystemExit(f'VERSION ({version}) != AppVersion.appVersion ({constants["appVersion"]})')
    repo_manifest = json.loads((root / 'Extension/manifest.json').read_text())
    if repo_manifest.get('version') != constants['extensionVersion']:
        raise SystemExit('Extension/manifest.json version != AppVersion.extensionVersion')
    origin_match = EXTENSION_ID_RE.match(constants['extensionAllowedOrigin'])
    if not origin_match:
        raise SystemExit('AppVersion.extensionAllowedOrigin is not a chrome-extension://<id>/ origin')
    return version, repo_manifest, constants, origin_match.group(1)


def write_wrapper(wrapper, app_path, host_path):
    """Same wrapper format as scripts/install_native_host.sh."""
    wrapper.parent.mkdir(parents=True, exist_ok=True)
    wrapper.write_text(
        '#!/bin/bash\n'
        '# Generated by scripts/install_release.py (same template as install_native_host.sh).\n'
        '# Chromium launches this wrapper instead of the binary directly so the host\n'
        '# knows which app bundle to launch.\n'
        f'export IDM_APP_PATH="{app_path}"\n'
        f'exec "{host_path}" "$@"\n')
    os.chmod(wrapper, 0o700)


def install(stage):
    root = Path(__file__).resolve().parent.parent
    version, repo_manifest, constants, origin_extension_id = expected_identity(root)
    app_name = APP_NAME
    source_app = stage / app_name
    if not source_app.is_dir():
        raise SystemExit(f'Staged app not found: {source_app}')
    info = plistlib.loads((source_app / 'Contents/Info.plist').read_bytes())
    manifest = json.loads((stage / 'Extension/manifest.json').read_text())
    digest = hashlib.sha256(base64.b64decode(manifest['key'])).hexdigest()[:32]
    extension_id = ''.join(chr(97 + int(letter, 16)) for letter in digest)
    problems = []
    if info.get('CFBundleShortVersionString') != version:
        problems.append(f'staged app version {info.get("CFBundleShortVersionString")!r} != VERSION {version!r}')
    if info.get('CFBundleIdentifier') != constants['bundleIdentifier']:
        problems.append('staged CFBundleIdentifier != AppVersion.bundleIdentifier')
    if info.get('CFBundleExecutable') != constants['appExecutableName']:
        problems.append('staged CFBundleExecutable != AppVersion.appExecutableName')
    if manifest.get('version') != constants['extensionVersion']:
        problems.append(f'staged extension version {manifest.get("version")!r} != AppVersion.extensionVersion {constants["extensionVersion"]!r}')
    if manifest.get('version') != repo_manifest.get('version'):
        problems.append('staged extension version != repo Extension/manifest.json version')
    if extension_id != origin_extension_id:
        problems.append(f'extension id {extension_id} != AppVersion origin id {origin_extension_id}')
    if problems:
        raise SystemExit('Release version/extension identity mismatch: ' + '; '.join(problems))
    subprocess.run(['codesign', '--verify', '--deep', '--strict', str(source_app)], check=True)
    if subprocess.run(['pgrep', '-f', '/Contents/MacOS/InternetDownloader$'], stdout=subprocess.DEVNULL).returncode == 0:
        raise SystemExit('Quit Internet Downloader after all jobs finish, then install again')
    database = Path.home() / 'Library/Application Support/InternetDownloader/downloader.sqlite3'
    connection = sqlite3.connect(database)
    if connection.execute("select count(*) from tasks where status in ('pending','downloading','assembling','needs_confirmation')").fetchone()[0]:
        raise SystemExit('Pending/active browser or HTTP jobs prevent rollout')
    backup = root / '.runtime' / ('rollout-' + datetime.now().strftime('%Y%m%d-%H%M%S'))
    backup.mkdir(parents=True, mode=0o700)
    with sqlite3.connect(backup / 'before.sqlite3') as target:
        connection.backup(target)
    os.chmod(backup / 'before.sqlite3', 0o600)
    columns = [row[1] for row in connection.execute('pragma table_info(tasks)')]
    rows = [dict(zip(columns, row)) for row in connection.execute('select * from tasks')]
    outputs = []
    for row in rows:
        path = Path(row['destination_folder']) / row['filename']
        if path.is_file():
            outputs.append({'id': row['id'], 'path': str(path), 'bytes': path.stat().st_size, 'sha256': checksum(path)})
    state = {'columns': columns, 'rows': {row['id']: hashlib.sha256(json.dumps(row, sort_keys=True).encode()).hexdigest() for row in rows}, 'outputs': outputs}
    state_path = backup / 'before-state.json'
    state_path.write_text(json.dumps(state, indent=2)); os.chmod(state_path, 0o600)
    host = Path.home() / 'Library/Application Support/Google/Chrome/NativeMessagingHosts' / (constants['nativeHostName'] + '.json')
    wrapper = Path.home() / 'Library/Application Support/InternetDownloader/native-host-wrapper.sh'
    if host.exists():
        shutil.copy2(host, backup / 'native-host-before.json')
    if wrapper.exists():
        shutil.copy2(wrapper, backup / 'native-host-wrapper-before.sh')
    dist = root / 'dist'; dist.mkdir(exist_ok=True)
    # Prepare all replacements before moving the installed release.
    replacements = []
    for name in [app_name, 'Extension', 'Internet-Downloader-Extension.zip']:
        source = stage / name
        next_path = dist / (name + '.next')
        if next_path.exists():
            raise SystemExit('A previous staging replacement remains: ' + str(next_path))
        if source.is_dir():
            shutil.copytree(source, next_path)
        else:
            shutil.copy2(source, next_path)
        replacements.append((name, next_path))
    if subprocess.run(['pgrep', '-f', '/Contents/MacOS/InternetDownloader$'], stdout=subprocess.DEVNULL).returncode == 0 or connection.execute("select count(*) from tasks where status in ('pending','downloading','assembling','needs_confirmation')").fetchone()[0]:
        for _, next_path in replacements:
            if next_path.is_dir():
                shutil.rmtree(next_path)
            else:
                next_path.unlink()
        raise SystemExit('App/jobs changed while preparing; existing release preserved')
    for name, next_path in replacements:
        target = dist / name
        if target.exists():
            target.rename(backup / name)
        next_path.rename(target)
    # The installed helper lives in dist; when the wrapper created by
    # install_native_host.sh exists, keep routing Chromium through it so
    # IDM_APP_PATH always names the bundle that was just installed.
    installed_app = dist / app_name
    installed_host = installed_app / HOST_BINARY_RELATIVE
    if wrapper.exists():
        write_wrapper(wrapper, installed_app, installed_host)
        manifest_path = wrapper
    else:
        manifest_path = installed_host
    host.parent.mkdir(parents=True, exist_ok=True)
    host.write_text(json.dumps({
        'name': constants['nativeHostName'],
        'description': f"Internet Downloader browser protocol {constants['protocolVersion']}",
        'path': str(manifest_path),
        'type': 'stdio',
        'allowed_origins': [constants['extensionAllowedOrigin']],
    }, indent=2) + '\n')
    os.chmod(host, 0o600)
    print(json.dumps({'appVersion': version, 'extensionVersion': manifest['version'],
                      'nativeHostManifest': str(host), 'nativeHostPath': str(manifest_path),
                      'backup': str(backup), 'originalRows': len(rows), 'outputs': len(outputs)}))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--stage', type=Path, required=True)
    install(parser.parse_args().stage.resolve())
